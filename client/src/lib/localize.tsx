const LANG_STORAGE_KEY = "resiliencehub_lang";

export const getInitialLanguage = (): string => {
  if (typeof window === "undefined") return "en";
  
  // 1. Check localStorage
  const savedLang = localStorage.getItem(LANG_STORAGE_KEY);
  if (savedLang === "en" || savedLang === "ar") {
    return savedLang;
  }
  
  // 2. Check window.Localize if initialized
  if (window.Localize && typeof window.Localize.getLanguage === "function") {
    const localizeLang = window.Localize.getLanguage();
    if (localizeLang === "en" || localizeLang === "ar") {
      return localizeLang;
    }
  }
  
  return "en";
};

export const applyLanguageDOM = (lang: string) => {
  if (typeof document === "undefined") return;
  
  document.documentElement.lang = lang;
  if (lang === "ar") {
    document.documentElement.dir = "rtl";
    document.documentElement.classList.add("rtl");
    document.documentElement.classList.remove("ltr");
  } else {
    document.documentElement.dir = "ltr";
    document.documentElement.classList.add("ltr");
    document.documentElement.classList.remove("rtl");
  }
};

// Define Context interface
interface LocalizationContextProps {
  currentLanguage: string;
  setLanguage: (lang: "en" | "ar") => void;
  t: (key: string) => string;
  tNum: (num: string | number) => string;
  isRTL: boolean;
}

const LocalizationContext = createContext<LocalizationContextProps | undefined>(undefined);

export const LocalizationProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [currentLanguage, setCurrentLanguageState] = useState<string>(getInitialLanguage);

  useEffect(() => {
    // Apply DOM attributes on mount
    applyLanguageDOM(currentLanguage);

    // Sync with LocalizeJS callback when language changes externally
    if (window.Localize && typeof window.Localize.on === "function") {
      const handleSetLanguage = (data: { to: string }) => {
        if (data && (data.to === "en" || data.to === "ar")) {
          setCurrentLanguageState(data.to);
          localStorage.setItem(LANG_STORAGE_KEY, data.to);
          applyLanguageDOM(data.to);
        }
      };
      
      try {
        window.Localize.on("setLanguage", handleSetLanguage);
      } catch (e) {
        console.warn("Failed to subscribe to LocalizeJS setLanguage event: ", e);
      }
    }
  }, []);

  const setLanguage = (lang: "en" | "ar") => {
    setCurrentLanguageState(lang);
    localStorage.setItem(LANG_STORAGE_KEY, lang);
    applyLanguageDOM(lang);

    // Call LocalizeJS frontend API
    if (window.Localize && typeof window.Localize.setLanguage === "function") {
      try {
        window.Localize.setLanguage(lang);
      } catch (e) {
        console.warn("LocalizeJS setLanguage call failed: ", e);
      }
    }
  };

  const t = (key: string): string => {
    const langDict = translations[currentLanguage];
    if (langDict && langDict[key] !== undefined) {
      return langDict[key];
    }
    return key;
  };

  const tNum = (num: string | number): string => {
    if (currentLanguage === "ar") {
      const arabicNumerals = ["٠", "١", "٢", "٣", "٤", "٥", "٦", "٧", "٨", "٩"];
      return String(num)
        .replace(/[0-9]/g, (w) => arabicNumerals[Number(w)])
        .replace(/%/g, "٪");
    }
    return String(num);
  };

  return (
    <LocalizationContext.Provider
      value={{
        currentLanguage,
        setLanguage,
        t,
        tNum,
        isRTL: currentLanguage === "ar",
      }}
    >
      {children}
    </LocalizationContext.Provider>
  );
};

export const useLocalization = () => {
  const context = useContext(LocalizationContext);
  if (context === undefined) {
    // Graceful fallback to avoid crashes if used outside the provider
    return {
      currentLanguage: "en",
      setLanguage: () => {},
      t: (key: string) => key,
      tNum: (num: string | number) => String(num),
      isRTL: false,
    };
  }
  return context;
};

// Global in-memory cache for dynamic database-sourced translations
const dynamicTranslationCache = new Map<string, string>();

interface DynamicTranslatorProps {
  text: string | null | undefined;
  className?: string;
}

/**
 * A luxury bilingual component that handles real-time dynamic translation of English
 * user/database text into Arabic using OpenAI. Uses strict memory caching to eliminate
 * redundant API calls and renders an elegant, pulse-animation shimmer while loading.
 */
export const DynamicTranslator: React.FC<DynamicTranslatorProps> = ({ text, className }) => {
  const { currentLanguage } = useLocalization();
  const [translatedText, setTranslatedText] = useState<string>("");
  const [isLoading, setIsLoading] = useState<boolean>(false);

  useEffect(() => {
    if (!text || typeof text !== "string" || text.trim() === "") {
      setTranslatedText("");
      return;
    }

    // Since original text in database is in English, immediately render LTR English
    if (currentLanguage !== "ar") {
      setTranslatedText(text);
      return;
    }

    // Check strict memory cache first to avoid repetitive API hits
    if (dynamicTranslationCache.has(text)) {
      setTranslatedText(dynamicTranslationCache.get(text) || text);
      return;
    }

    let isMounted = true;

    const fetchTranslation = async () => {
      setIsLoading(true);
      try {
        const response = await fetch("/api/translate", {
          method: "POST",
          headers: {
            "Content-Type": "application/json",
          },
          body: JSON.stringify({ text, targetLang: "ar" }),
          credentials: "include",
        });

        if (!response.ok) {
          throw new Error(`Failed to translate. Status: ${response.status}`);
        }

        const data = await response.json();
        const result = data.translation || text;

        dynamicTranslationCache.set(text, result);
        if (isMounted) {
          setTranslatedText(result);
        }
      } catch (error) {
        console.error("DynamicTranslator translation error:", error);
        // Fallback to original text on error
        if (isMounted) {
          setTranslatedText(text);
        }
      } finally {
        if (isMounted) {
          setIsLoading(false);
        }
      }
    };

    fetchTranslation();

    return () => {
      isMounted = false;
    };
  }, [text, currentLanguage]);

  if (!text) return null;

  if (isLoading) {
    return (
      <span className={`inline-block animate-pulse bg-slate-200 dark:bg-slate-800 rounded select-none min-w-[70px] h-[1.1em] align-middle opacity-60 ${className || ""}`} />
    );
  }

  return <span className={className}>{translatedText}</span>;
};

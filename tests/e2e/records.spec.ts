test("reframe: failed submission retains choices for automatic retry and persists once", async ({ page }) => {
  await login(page.request);
  const response = await page.request.post(`/api/users/${ids.client}/thoughts`, {
    headers: { Origin: process.env.E2E_BASE_URL! },
    data: { automaticThoughts: thought, cognitiveDistortions: ["catastrophizing"] },
  });
  expect(response.status()).toBe(201);
  const record = await response.json();
  // Only AI-generated content is deterministic; auth, thought reads and result saves are real.
  await page.route("**/practice-scenarios?*", route => route.fulfill({ json: {
    thoughtContent: thought, generalFeedback: "Synthetic practice feedback",
    scenarios: [{
      scenario: "Synthetic scenario: a fictional presentation is tomorrow.",
      cognitiveDistortion: "catastrophizing", emotionCategory: "fear",
      options: [
        { text: "Synthetic balanced answer", isCorrect: true, explanation: "Preparation can help." },
        { text: "Synthetic unhelpful answer", isCorrect: false, explanation: "This assumes the worst." },
      ],
    }],
  } }));
  let attempts = 0;
  let original: any;
  const before = await count("reframe_practice_results");
  await page.route("**/api/reframe-coach/results", async route => {
    attempts++;
    const payload = route.request().postDataJSON();
    if (attempts === 1) {
      original = payload;
      return route.fulfill({ status: 503, json: { message: "Synthetic save failure" } });
    }
    expect(payload).toEqual(original);
    expect(await count("reframe_practice_results")).toBe(before);
    return route.continue();
  });
  await page.goto(`/reframe-coach/practice/quick/${record.id}`);
  await page.getByText("Synthetic balanced answer", { exact: true }).click();
  const saved = page.waitForResponse(response => response.url().endsWith("/api/reframe-coach/results") && response.status() === 201);
  await page.getByRole("button", { name: "See Results" }).click();
  const result = (await (await saved).json()).result;
  expect(result.userChoices).toEqual(original.userChoices);
  expect(result.userId).toBe(ids.client);
  await expect.poll(() => count("reframe_practice_results")).toBe(before + 1);
  expect(attempts).toBe(2);
});

test("persisted records: owner, assigned therapist and admin allowed; unrelated users and anonymous denied", async ({ playwright }) => {
  const owner = await playwright.request.newContext({ baseURL: process.env.E2E_BASE_URL });
  await login(owner);
  const origin = { Origin: process.env.E2E_BASE_URL! };
  const cases = [
    { name: "emotions", write: `/api/users/${ids.client}/emotions`, read: `/api/users/${ids.client}/emotions`,
      data: { coreEmotion: "fear", intensity: 4, situation: writing }, field: "situation", value: writing },
    { name: "thoughts", write: `/api/users/${ids.client}/thoughts`, read: `/api/users/${ids.client}/thoughts`,
      data: { automaticThoughts: thought, cognitiveDistortions: [] }, field: "automaticThoughts", value: thought },
    { name: "journal", write: "/api/journal", read: `/api/users/${ids.client}/journal`,
      data: { title: "Synthetic access journal", content: writing }, field: "content", value: writing },
    { name: "goals", write: `/api/users/${ids.client}/goals`, read: `/api/users/${ids.client}/goals`,
      data: { title: "Synthetic access goal", specific: writing, measurable: writing, achievable: writing, relevant: writing, timebound: writing }, field: "title", value: "Synthetic access goal" },
    { name: "reframe", write: "/api/reframe-coach/results", read: `/api/users/${ids.client}/reframe-coach/results`,
      data: { score: 100, correctAnswers: 1, totalQuestions: 1, scenarioData: [], userChoices: [] }, field: "score", value: 100 },
  ];
  try {
    for (const record of cases) {
      // A forged body identity must never redirect a save to another account.
      const saved = await owner.post(record.write, { headers: origin, data: { ...record.data, userId: ids.otherClient } });
      expect(saved.status(), record.name).toBe(201);
      const body = await saved.json();
      expect((body.result || body).userId).toBe(ids.client);
      const id = (body.result || body).id;
      const urls = [record.read];
      if (record.name === "journal") urls.push(`/api/journal/${id}`);
      if (record.name === "thoughts") urls.push(`/api/thoughts/${id}`);
      for (const role of ["client", "assigned", "unrelated", "admin", "otherClient", "anonymous"]) {
        const actor = await playwright.request.newContext({ baseURL: process.env.E2E_BASE_URL });
        try {
          if (role !== "anonymous") await login(actor, role);
          for (const url of urls) {
            const response = await actor.get(url);
            const allowed = ["client", "assigned", "admin"].includes(role);
            expect(response.status(), `${record.name} ${role} ${url}`).toBe(allowed ? 200 : role === "anonymous" ? 401 : 403);
            const data = await response.json();
            if (allowed) {
              const rows = Array.isArray(data) ? data : [data];
              expect(rows).toEqual(expect.arrayContaining([expect.objectContaining({ id, userId: ids.client, [record.field]: record.value })]));
            } else {
              expect(JSON.stringify(data)).not.toContain(writing);
              expect(JSON.stringify(data)).not.toContain(thought);
            }
          }
          // Unrelated users cannot create records for the client via URL identity.
          if (role === "anonymous" || (["unrelated", "otherClient"].includes(role) && ["emotions", "thoughts", "goals"].includes(record.name))) {
            const blocked = await actor.post(record.write, { headers: origin, data: record.data });
            expect(blocked.status()).toBe(role === "anonymous" ? 401 : 403);
          }
        } finally { await actor.dispose(); }
      }
    }
  } finally { await owner.dispose(); }
});

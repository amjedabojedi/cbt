test("journal: failed creation retains both fields, retry and tag completion persist", async ({ page }) => {
  await login(page.request);
  await start(page, "/journal");
  await page.getByTestId("input-journal-title").fill("Synthetic journal title");
  await next(page);
  await page.getByTestId("textarea-journal-content").fill(writing);
  const saved = await failThenRetry(page, "/api/journal", "journal_entries", () => next(page),
    async () => {
      await expect(page.getByTestId("textarea-journal-content")).toHaveValue(writing);
      await page.getByTestId("button-previous-step").click();
      await expect(page.getByTestId("input-journal-title")).toHaveValue("Synthetic journal title");
      await next(page);
    });
  expect(saved.content).toBe(writing);
  await expect(page.getByTestId("step-review")).toBeVisible();
  await page.getByPlaceholder("Enter a custom tag...").fill("synthetic-tag");
  await page.getByPlaceholder("Enter a custom tag...").press("Enter");
  const tagsEndpoint = `/api/journal/${saved.id}/tags`;
  let tagAttempts = 0;
  await page.route(`**${tagsEndpoint}`, route => {
    tagAttempts++;
    expect(route.request().postDataJSON()).toEqual({ selectedTags: ["synthetic-tag"] });
    return tagAttempts === 1
      ? route.fulfill({ status: 503, json: { message: "Synthetic tag save failure" } })
      : route.continue();
  });
  const failedTags = page.waitForResponse(response => response.url().endsWith(tagsEndpoint) && response.status() === 503);
  await page.getByTestId("button-submit-wizard").click();
  await failedTags;
  await expect(page.getByTestId("step-review")).toContainText(/synthetic-tag/i);
  const tags = page.waitForResponse(response => response.url().endsWith(`/api/journal/${saved.id}/tags`) && response.ok());
  await page.getByTestId("button-submit-wizard").click();
  await tags;
  expect(tagAttempts).toBe(2);
  expect(await (await page.request.get(`/api/journal/${saved.id}`)).json()).toMatchObject({
    content: writing, userSelectedTags: ["synthetic-tag"],
  });
});


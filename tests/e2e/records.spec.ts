import { test, expect, type APIRequestContext, type Page } from "@playwright/test";
import { Pool } from "pg";

type Fixtures = Record<"client" | "otherClient" | "assigned" | "unrelated" | "admin", number>;
let ids: Fixtures;
const password = "Synthetic-test-password-42";
const writing = "Synthetic practice: preparing for a fictional presentation tomorrow.";
const thought = "Synthetic thought: I might struggle with this fictional presentation.";

test.beforeAll(async ({ request }) => {
  ids = await (await request.get("/__e2e/ready")).json();
});
async function login(request: APIRequestContext, role = "client") {
  const response = await request.post("/api/auth/login", {
    headers: { Origin: process.env.E2E_BASE_URL! },
    data: { username: `e2e-${role}`, password },
  });
  expect(response.status()).toBe(200);
  expect((await (await request.get("/api/auth/me")).json()).id).toBe(ids[role as keyof Fixtures]);
}
test.beforeEach(async ({ page }) => {
  // Block third-party analytics, fonts, AI and email from the browser too.
  await page.route("**/*", route =>
    new URL(route.request().url()).origin === process.env.E2E_BASE_URL
      ? route.continue() : route.abort("blockedbyclient"));
});
async function next(page: Page) {
  await page.getByTestId("button-next-step").click();
}
async function start(page: Page, path: string) {
  await page.goto(path);
  await next(page);
}
async function count(table: string) {
  // URL is generated by the runner; it is never read from the parent workspace.
  const pool = new Pool({ connectionString: process.env.DATABASE_URL });
  try {
    const result = await pool.query(`select count(*)::int as count from ${table} where user_id = $1`, [ids.client]);
    return result.rows[0].count as number;
  } finally { await pool.end(); }
}
// A real HTTP failure reaches the UI; only the first write is intercepted.
// Every retry goes through real authentication, validation and PostgreSQL.
async function failThenRetry(page: Page, endpoint: string, table: string, submit: () => Promise<void>, retained: () => Promise<void>) {
  const before = await count(table);
  let attempts = 0;
  let payload: Record<string, unknown>;
  const stablePayload = (value: Record<string, unknown>) => {
    // "Use current time" deliberately evaluates at submission, not at typing.
    if (table === "emotion_records") {
      const { timestamp, ...writing } = value;
      expect(Number.isNaN(Date.parse(timestamp as string))).toBe(false);
      return writing;
    }
    return value;
  };
  await page.route(`**${endpoint}`, async route => {
    if (route.request().method() !== "POST") return route.continue();
    attempts++;
    if (attempts === 1) {
      payload = stablePayload(route.request().postDataJSON());
      return route.fulfill({ status: 503, json: { message: "Synthetic temporary save failure" } });
    }
    // Retry must contain exactly the user's original writing/choices.
    expect(stablePayload(route.request().postDataJSON())).toEqual(payload);
    return route.continue();
  });
  const failure = page.waitForResponse(response => response.url().endsWith(endpoint) && response.status() === 503);
  await submit();
  await failure;
  await retained();
  expect(await count(table)).toBe(before);
  const saved = page.waitForResponse(response =>
    response.url().endsWith(endpoint) && response.request().method() === "POST" && response.status() === 201);
  await submit();
  const body = await (await saved).json();
  await expect.poll(() => count(table)).toBe(before + 1);
  expect(attempts).toBe(2);
  return body;
}

test("emotion: failed save retains situation, retry persists and survives reload", async ({ page }) => {
  await login(page.request);
  await start(page, "/emotions");
  await page.locator("#emotion-search").fill("Nervous");
  await page.getByRole("option").first().click();
  await next(page);
  await next(page);
  await page.getByTestId("textarea-situation").fill(writing);
  await next(page);
  const saved = await failThenRetry(page, `/api/users/${ids.client}/emotions`, "emotion_records",
    () => page.getByTestId("button-submit-wizard").click(),
    async () => {
      await page.getByTestId("button-previous-step").click();
      await expect(page.getByTestId("textarea-situation")).toHaveValue(writing);
      await next(page);
    });
  expect(saved.situation).toBe(writing);
  await expect(page.getByRole("heading", { name: "Emotion Recorded Successfully!" })).toBeVisible();
  await page.reload();
  const records = await (await page.request.get(`/api/users/${ids.client}/emotions`)).json();
  expect(records).toEqual(expect.arrayContaining([expect.objectContaining({ id: saved.id, situation: writing })]));
});

